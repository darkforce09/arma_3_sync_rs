/// Console line for a managed repository error.
// Mirrors utils/RepositoryConsoleErrorPrinter.java:5-12
pub fn repository_managed_error(repository_name: &str, message: &str) -> String {
    format!("Repository: {repository_name}\n - {message}")
}

/// Console line for an unexpected repository error. Java also prints the stack trace; Rust
/// callers log the error chain at `error!` instead.
// Mirrors utils/RepositoryConsoleErrorPrinter.java:14-22
pub fn repository_unexpected_error(repository_name: &str) -> String {
    format!("Repository: {repository_name} - An unexpected error has occured.")
}

/// Text of the unexpected-error report a user can export (Java's `ArmA3Sync-log.txt`).
///
/// All inputs are plain strings so this crate needs no dependencies: `version` and `target`
/// come from `a3s_build_info`, `date` from `a3s_format::datetime_medium`, `chain` from
/// [`crate::format_chain_lines`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ErrorReport<'a> {
    /// Application version.
    pub version: &'a str,

    /// Git hash of the build.
    pub git_hash: &'a str,

    /// Target triple of the build.
    pub target: &'a str,

    /// Operating system name.
    pub os: &'a str,

    /// Date of the report, already formatted.
    pub date: &'a str,

    /// Error chain, one error per line.
    pub chain: String,
}

impl ErrorReport<'_> {
    /// Renders the report. Java's `JRE installed version` line and stack trace are replaced by
    /// the build line and the error chain.
    // Mirrors ui/ErrorLogDialog.java:35-55 and service/CommonService.java:111-118
    pub fn render(&self) -> String {
        let Self {
            version,
            git_hash,
            target,
            os,
            date,
            chain,
        } = self;
        format!(
            "Generated by Arma3Sync {version}\n{date}\n\n\
             An unexpected error has occured.\n\n\
             ArmA3Sync Installed version = {version}\n\
             Build = {git_hash} ({target})\n\
             OS Name = {os}\n\n\
             Error chain:\n{chain}\n"
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_e6_console_lines() {
        assert_eq!(
            repository_managed_error("WOG", "x"),
            "Repository: WOG\n - x"
        );
        assert_eq!(
            repository_unexpected_error("WOG"),
            "Repository: WOG - An unexpected error has occured."
        );
    }

    #[test]
    fn a_e6_error_report_golden() {
        let report = ErrorReport {
            version: "0.1.0-alpha.1",
            git_hash: "abc1234",
            target: "x86_64-unknown-linux-gnu",
            os: "linux",
            date: "Oct 10, 2026, 2:05:09 PM",
            chain: "download failed\nHTTP: inner failure".to_owned(),
        };
        assert_eq!(
            report.render(),
            "Generated by Arma3Sync 0.1.0-alpha.1\n\
             Oct 10, 2026, 2:05:09 PM\n\
             \n\
             An unexpected error has occured.\n\
             \n\
             ArmA3Sync Installed version = 0.1.0-alpha.1\n\
             Build = abc1234 (x86_64-unknown-linux-gnu)\n\
             OS Name = linux\n\
             \n\
             Error chain:\n\
             download failed\n\
             HTTP: inner failure\n"
        );
    }
}
